ALTER TABLE visits
  ADD COLUMN scheduled_at DATETIME NULL,
  ADD COLUMN duration_minutes INT NOT NULL DEFAULT 45,
  ADD COLUMN status VARCHAR(30) NOT NULL DEFAULT 'SCHEDULED',
  ADD COLUMN reminder_sent TINYINT(1) NOT NULL DEFAULT 0;

UPDATE visits
SET scheduled_at = TIMESTAMP(visit_date, '09:00:00'),
    status = CASE WHEN visit_date < CURRENT_DATE() THEN 'COMPLETED' ELSE 'SCHEDULED' END
WHERE scheduled_at IS NULL;

ALTER TABLE payments
  MODIFY COLUMN paid_at DATETIME NULL,
  ADD COLUMN due_at DATETIME NULL,
  ADD COLUMN status VARCHAR(30) NOT NULL DEFAULT 'PAID';

UPDATE payments
SET status = CASE WHEN paid_at IS NOT NULL THEN 'PAID' ELSE 'PENDING' END
WHERE status IS NULL OR status = '';
